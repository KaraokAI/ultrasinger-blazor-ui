"""Pin our resolution to the versions UltraSinger itself was tested with.

UltraSinger's pyproject.toml leaves most dependencies unpinned and relies on its own uv.lock;
resolving it fresh picks up newer releases with breaking API changes (e.g. swift-f0 0.3
dropping SwiftF0(fmin=...)). This copies every version from ../UltraSinger/uv.lock into
[tool.uv] constraint-dependencies in pyproject.toml.

Re-run after bumping the submodule, then `uv lock && uv sync`:
    python3 update_constraints.py
"""

import pathlib
import re
import tomllib

HERE = pathlib.Path(__file__).parent
UPSTREAM_LOCK = HERE.parent / "UltraSinger" / "uv.lock"
PYPROJECT = HERE / "pyproject.toml"

BEGIN = "# BEGIN generated by update_constraints.py - do not edit by hand"
END = "# END generated by update_constraints.py"

# The upstream project itself, plus the YouTube download stack: that has to track YouTube's
# changes rather than UltraSinger's, and a months-old yt-dlp simply stops working.
SKIP = {"ultrasinger", "yt-dlp", "yt-dlp-ejs", "deno"}

lock = tomllib.loads(UPSTREAM_LOCK.read_text())

# New yt-dlp releases raise their floors on these (certifi especially), so they're freed up
# along with it. They're general-purpose HTTP/crypto libraries, so the risk is low.
for package in lock["package"]:
    if package["name"] == "yt-dlp":
        for dependency in package.get("optional-dependencies", {}).get("default", []):
            SKIP.add(dependency["name"])
pins = sorted(
    {
        f'{package["name"]}=={package["version"]}'
        for package in lock["package"]
        if package["name"] not in SKIP
        and "version" in package
        # Only registry packages; git/path sources have no meaningful version pin.
        and "registry" in package.get("source", {})
    }
)

# "torch==2.8.0" also matches the local version "2.8.0+cu128" from the PyTorch index.
block = "\n".join(
    [BEGIN, "constraint-dependencies = [", *(f'    "{pin}",' for pin in pins), "]", END]
)

text = PYPROJECT.read_text()
pattern = re.compile(re.escape(BEGIN) + ".*?" + re.escape(END), re.S)

if pattern.search(text):
    text = pattern.sub(lambda _: block, text)
else:
    text = text.replace("[tool.uv]\n", "[tool.uv]\n" + block + "\n", 1)

PYPROJECT.write_text(text)
print(f"Wrote {len(pins)} constraints from {UPSTREAM_LOCK}")
